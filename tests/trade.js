const fs = require('fs'), vm = require('vm'), assert = require('assert');
const context = vm.createContext({});
vm.runInContext(fs.readFileSync('public/trade.js','utf8')+'\nthis.details=tradeDetails;',context);
const trade = JSON.parse(fs.readFileSync('public/example.json','utf8')).trade;
trade.notes='<img src=x onerror=alert(1)>';
const html=context.details.html(trade,'SHORT');
assert(html.includes('75000')&&html.includes('75450')&&html.includes('74500')&&html.includes('74000'));
assert(!html.includes('<img')&&html.includes('&lt;img'));
const body=context.details.notification({name:'test',action:'SHORT',trade});
assert(body.includes('75000')&&body.includes('75450')&&body.includes('SHORT'));
assert(context.details.html(null,'LONG').length>0);
trade.entry={type:'MARKET',reference_price:74800};
assert(context.details.html(trade,'SHORT').includes('74800'));
const cancelled={type:'cancelled',name:'test',reason:'cancel reason',action:'SHORT'};
assert(context.details.notification(cancelled).includes('cancel reason'));
assert(!context.details.notification(cancelled).includes('75000'));
assert(context.details.title(cancelled)!=='SHORT');
assert(context.details.status({config:{enabled:true},state:{cancelled_at:100,cancel_reason:'cancel reason'}}).includes('cancel reason'));
console.log('Trade rendering, notification details and escaping passed.');
